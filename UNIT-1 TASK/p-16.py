print("1. Creating Empty List :-")
list1 = []
print(list1)

print("\n2. Creating List with Elements :-")
list2 = [10, 20, 30, 40]
print(list2)

print("\n3. Creating List with Different Data Types :-")
list3 = [10, "Python", 5.5, True]
print(list3)

print("\n4. Creating List using list() :-")
list4 = list((1, 2, 3, 4))
print(list4)

print("\n5. Creating List using range() :-")
list5 = list(range(1, 6))
print(list5)