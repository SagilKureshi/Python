s = "SAGIL"

print("String =", s)

print("\nPositive Indexing :-")
print("s[0] =", s[0])
print("s[1] =", s[1])
print("s[2] =", s[2])

print("\nNegative Indexing :-")
print("s[-1] =", s[-1])
print("s[-2] =", s[-2])
print("s[-3] =", s[-3])

print("\nSlice Operator :-")
print("s[0:3] =", s[0:3])
print("s[2:5] =", s[2:5])
print("s[:4] =", s[:4])
print("s[2:] =", s[2:])
print("s[:] =", s[:])