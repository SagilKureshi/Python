print("1. Creating Empty Tuple :-")
t1 = ()
print(t1)

print("\n2. Creating Tuple with Elements :-")
t2 = (10, 20, 30, 40)
print(t2)

print("\n3. Creating Tuple with Different Data Types :-")
t3 = (10, "Python", 5.5, True)
print(t3)

print("\n4. Creating Tuple using tuple() :-")
t4 = tuple([1, 2, 3, 4])
print(t4)

print("\n5. Creating Tuple using range() :-")
t5 = tuple(range(1, 6))
print(t5)

print("\n6. Creating Single Element Tuple :-")
t6 = (10,)
print(t6)