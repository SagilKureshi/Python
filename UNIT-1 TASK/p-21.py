print("1. Creating Empty Set :-")
s1 = set()
print(s1)

print("\n2. Creating Set with Elements :-")
s2 = {10, 20, 30, 40}
print(s2)

print("\n3. Creating Set with Different Data Types :-")
s3 = {10, "Python", 5.5, True}
print(s3)

print("\n4. Creating Set using set() :-")
s4 = set([1, 2, 3, 4])
print(s4)

print("\n5. Creating Set from String :-")
s5 = set("Sagil")
print(s5)

print("\n6. Creating Set using range() :-")
s6 = set(range(1, 6))
print(s6)