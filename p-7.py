# if statement

a = 10

if a > 5:
    print("a is greater than 5")


# if-else statement

num = 10

if num % 2 == 0:
    print("Number is Even")
else:
    print("Number is Odd")


# if-elif-else statement

marks = 75

if marks >= 80:
    print("Grade A")
elif marks >= 60:
    print("Grade B")
elif marks >= 40:
    print("Grade C")
else:
    print("Fail")   